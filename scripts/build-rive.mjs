#!/usr/bin/env node
// Regenerates rive/le-recu-paper/scene.rml, compiles it with the installed Rive CLI and
// publishes the runtime asset to public/rive/. Writes rive/le-recu-paper/PROVENANCE.json.
//   npm run rive:build          # needs the `rive` CLI on PATH (see rive/le-recu-paper/AGENTS.md)
//   node scripts/build-rive.mjs --check   # only verify the committed asset matches its provenance
import { spawnSync } from "node:child_process"
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { createHash } from "node:crypto"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const project = join(root, "rive", "le-recu-paper")
const built = join(project, "build", "le-recu-paper.riv")
const published = join(root, "public", "rive", "le-recu-paper.riv")
const provenancePath = join(project, "PROVENANCE.json")
const sha256 = (file) => createHash("sha256").update(readFileSync(file)).digest("hex")

if (process.argv.includes("--check")) {
  const p = JSON.parse(readFileSync(provenancePath, "utf8"))
  const actual = sha256(published)
  if (actual !== p.sha256) {
    console.error(`public/rive/le-recu-paper.riv (${actual}) does not match PROVENANCE.json (${p.sha256}); run npm run rive:build`)
    process.exit(1)
  }
  console.log(`ok ${actual}`)
  process.exit(0)
}

function run(cmd, args) {
  const r = spawnSync(cmd, args, { cwd: root, encoding: "utf8", shell: process.platform === "win32" && cmd === "rive" })
  if (r.status !== 0) {
    console.error(`${cmd} ${args.join(" ")} failed\n${r.stdout}\n${r.stderr}`)
    process.exit(r.status ?? 1)
  }
  return r.stdout.trim() + r.stderr.trim()
}

const cli = run("rive", ["--version"])
run("node", [join(project, "tools", "gen-scene.mjs"), "dry", project])
run("rive", [project, "--verify"])
run("rive", [project, "--once"])
if (!existsSync(built)) throw new Error("rive --once produced no .riv")
mkdirSync(dirname(published), { recursive: true })
copyFileSync(built, published)

const provenance = {
  artifact: "public/rive/le-recu-paper.riv",
  source: "rive/le-recu-paper/scene.rml (generated by tools/gen-scene.mjs, direction: dry, V1.5 inline ink)",
  sha256: sha256(published),
  bytes: readFileSync(published).length,
  rive_cli: cli,
  scripts: 0,
  signed: false,
  note: "No Luau/AnimaScript: the file carries no scripts, so an unsigned local build loads in web runtimes. Not pushed to or overwriting any Rive account file.",
}
writeFileSync(provenancePath, JSON.stringify(provenance, null, 2) + "\n")
console.log(JSON.stringify(provenance, null, 2))
